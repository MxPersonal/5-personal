drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products" on public.products for select to anon, authenticated using (is_active or (select private.is_admin()));
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

drop policy if exists "Users view own profile" on public.profiles;
create policy "Users view own profile" on public.profiles for select to authenticated using ((select auth.uid()) = id or (select private.is_admin()));
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

drop policy if exists "Users view own role" on public.user_roles;
create policy "Users view own role" on public.user_roles for select to authenticated using ((select auth.uid()) = user_id or (select private.is_admin()));
drop policy if exists "Admins update roles" on public.user_roles;
create policy "Admins update roles" on public.user_roles for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

drop policy if exists "Users manage own addresses" on public.addresses;
create policy "Users manage own addresses" on public.addresses for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Admins view addresses" on public.addresses;
create policy "Admins view addresses" on public.addresses for select to authenticated using ((select private.is_admin()));

drop policy if exists "Users view own orders" on public.orders;
create policy "Users view own orders" on public.orders for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Admins view orders" on public.orders;
create policy "Admins view orders" on public.orders for select to authenticated using ((select private.is_admin()));
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

drop policy if exists "Users view own order items" on public.order_items;
create policy "Users view own order items" on public.order_items for select to authenticated using (
  exists (select 1 from public.orders where orders.id = order_items.order_id and orders.user_id = (select auth.uid()))
);
drop policy if exists "Admins view order items" on public.order_items;
create policy "Admins view order items" on public.order_items for select to authenticated using ((select private.is_admin()));

